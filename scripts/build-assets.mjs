// Regenerates src/data/assets.js from whatever actually exists on disk.
// Run after adding or removing files under public/images.
//   node scripts/build-assets.mjs

import fs from "node:fs";
import path from "node:path";

const ROOT = "public/images";
const UPSTREAM = "https://shishuniketanmohali.org.in/static/images/";

function walk(dir, base = "") {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const abs = path.join(dir, entry.name);
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      // Pre-upscale originals are a backup, not site content.
      return entry.name === "_originals" ? [] : walk(abs, rel);
    }
    return /\.(jpe?g|png|gif|webp)$/i.test(entry.name) ? [rel] : [];
  });
}

const files = walk(ROOT).sort();
if (!files.length) throw new Error(`No images found under ${ROOT}`);

const byFolder = new Map();
for (const rel of files) {
  const folder = rel.includes("/") ? rel.slice(0, rel.indexOf("/")) : "root";
  if (!byFolder.has(folder)) byFolder.set(folder, []);
  byFolder.get(folder).push(rel);
}

const pub = (rel) => `/images/${rel.split("/").map(encodeURIComponent).join("/")}`;
const key = (rel) => rel.replace(/\.(jpe?g|png|gif|webp)$/i, "").replace(/[^\w]/g, "_");

const flat = ["root", "infra_pics", "news"];
const albums = ["Gallery", "Achievements"];

const lines = [
  "// GENERATED by scripts/build-assets.mjs — do not edit by hand.",
  `// Every path below exists on disk. Upstream origin: ${UPSTREAM}`,
  "",
  "export const assetManifest = [",
  ...files.map((rel) => `  { file: ${JSON.stringify(rel)}, path: ${JSON.stringify(pub(rel))}, source: ${JSON.stringify(UPSTREAM + rel)} },`),
  "];",
  "",
  "export const images = {",
  ...flat.flatMap((folder) => (byFolder.get(folder) ?? []).map((rel) => `  ${key(rel)}: ${JSON.stringify(pub(rel))},`)),
  "};",
  "",
  "export const albums = {",
  ...albums.flatMap((folder) => {
    const groups = new Map();
    for (const rel of byFolder.get(folder) ?? []) {
      const album = rel.split("/")[1];
      if (!groups.has(album)) groups.set(album, []);
      groups.get(album).push(rel);
    }
    return [...groups].map(
      ([album, list]) =>
        `  ${key(album)}: { folder: ${JSON.stringify(album)}, images: ${JSON.stringify(list.sort().map(pub))} },`
    );
  }),
  "};",
  "",
];

fs.writeFileSync("src/data/assets.js", lines.join("\n"));
console.log(`Wrote src/data/assets.js — ${files.length} images, ${byFolder.size} folders.`);
